    <div class="card explainer-card">
      <h2 class="card-title">Vad är 3:12-reglerna?</h2>
      <p>
        3:12-reglerna styr hur utdelning och kapitalvinst från fåmansbolag beskattas.
        Som ägare till ett fåmansbolag kan du ta ut utdelning till en lägre skattesats
        (20&nbsp;%) upp till ett visst belopp — det så kallade <strong>gränsbeloppet</strong>.
      </p>
      <p>
        Utdelning över gränsbeloppet beskattas istället som tjänsteinkomst (~50&nbsp;%)
        — upp till takregeln på 90&nbsp;×&nbsp;IBB per år, räknat för dig och dina närstående
        tillsammans. Därutöver beskattas den som kapital (30&nbsp;%).
      </p>
    </div>

    <div class="card explainer-card">
      <h2 class="card-title">Vad är gränsbelopp?</h2>
      <p>
        Gränsbeloppet är det maximala belopp du kan ta ut som lågbeskattad
        utdelning (20&nbsp;%) under ett år. Det beräknas som summan av tre delar:
      </p>
      <ul>
        <li><strong>Grundbelopp</strong> — din ägarandel × 4 × IBB (inkomstbasbeloppet)</li>
        <li><strong>Lönebaserat utrymme</strong> — 50&nbsp;% av din andel av bolagets lönesumma efter ett löneavdrag på 8 × IBB</li>
        <li><strong>Ränta på omkostnadsbelopp</strong> — (omkostnadsbelopp − 100&nbsp;000&nbsp;kr) × (statslåneräntan i slutet av november året innan + 9&nbsp;%)</li>
      </ul>
      <p>
        Oanvänt gränsbelopp sparas till nästa år (sparat utdelningsutrymme) men räknas inte längre upp — det är en av förändringarna i de nya 3:12-reglerna från 2026.
      </p>
    </div>

    <div class="card explainer-card">
      <h2 class="card-title">Varför holdingbolag?</h2>
      <p>
        Den stora fördelen med ett holdingbolag är <strong>skatteuppskov</strong>.
        Utdelning från driftsbolaget till holdingbolaget är skattefri
        (näringsbetingade andelar), vilket innebär att du kan återinvestera
        hela vinsten utan att betala privatskatt — du betalar först när du
        faktiskt tar ut pengarna privat.
      </p>
      <p>
        Det ger en kraftig ränta-på-ränta-effekt över tid. Holdingbolaget
        fungerar också som en "kassa" om du säljer driftsbolaget — vinsten på
        aktierna är skattefri för holdingbolaget och kan återinvesteras i ny verksamhet.
      </p>
    </div>

    <div class="card explainer-card">
      <h2 class="card-title">Direkt ägande vs holdingbolag</h2>
      <ul>
        <li><strong>Grundbelopp</strong> — större via holdingbolag om du äger mindre än 100&nbsp;% av bolaget. Du äger holdingbolaget helt och får därför hela grundbeloppet (4&nbsp;×&nbsp;IBB), mot bara din andel vid direkt ägande.</li>
        <li><strong>Lönebaserat utrymme</strong> — lika stort i båda fallen, förutsatt att driftsbolaget är dotterföretag till holdingbolaget, dvs. att holdingbolaget har mer än hälften av rösterna eller på annat sätt bestämmande inflytande, t.ex. rätt att utse mer än halva styrelsen. Annars räknas bolagets löner inte med.</li>
        <li><strong>Skatt vid uttag</strong> — samma regler: 20&nbsp;% inom gränsbeloppet, tjänstebeskattning på överskott.</li>
        <li><strong>Fördel holding</strong> — du styr när du tar ut privat; utdelning och aktievinster från driftsbolaget kommer in skattefritt i mellanledet.</li>
        <li><strong>Nackdel holding</strong> — ett bolag extra innebär mer bokföring, årsredovisning och initiala bolagskostnader.</li>
      </ul>
      <p>
        Kalkylatorn visar vilket upplägg ger störst gränsbelopp i din situation.
      </p>
    </div>

